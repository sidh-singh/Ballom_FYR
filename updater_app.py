"""
updater_app.py — SHA Signal Analysis updater service.

Usage:  python updater_app.py [demo|live]

Architecture
────────────
Forever Loop (runs 24×7):
  Step 1 — Load Fyers token from C:/Ballom_FYR/fyers_token.json
           (written by dev_scanner — NO re-auth here)
  Step 2 — Day-change detection → reload token + holidays
  Step 3 — Read CE/PE pairs from option_pairs.json / commodity_pairs.json
           (generated by dev_scanner)
  Step 4 — For each symbol pair, compute:
             • Signal SHA (length=3) for CE, PE, IDX
             • Trend SHA  (length=6) for CE, PE, IDX
             • Power, List, Crossover for both
             • GAP%  between Signal SHA and Trend SHA
             • SHA Relationship (DIVERGING / CONVERGING / PARALLEL / CLOSE)
  Step 5 — Dump all signal data to JSON state files so the dev branch
           dashboard can display SHA Signal Analysis in real-time

Output:
  C:/Ballom_FYR/state/<mode>/signal_state.json   — per-symbol SHA analysis
  C:/Ballom_FYR/state/<mode>/app_status.json      — updater lifecycle
  C:/Ballom_FYR/state/<mode>/strategy_log/         — scan/update events

Token sharing:  reads token from C:/Ballom_FYR/fyers_token.json
                (written by dev_scanner, refreshed daily at midnight)
"""

